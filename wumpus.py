from collections import deque
from dataclasses import dataclass

SIZE = 4
START = (1, 1)
HEADINGS = ((1, 0), (0, 1), (-1, 0), (0, -1))


def adjacent(cell):
    """Return valid neighboring cells."""
    x, y = cell
    return {
        (x + dx, y + dy)
        for dx, dy in HEADINGS
        if 1 <= x + dx <= SIZE and 1 <= y + dy <= SIZE
    }


@dataclass(frozen=True)
class Rule:
    requires: frozenset[str]
    action: str

    def applies(self, facts):
        return self.requires.issubset(facts)


RULES = (
    Rule(frozenset({"carrying", "home"}), "climb"),
    Rule(frozenset({"glitter", "searching"}), "grab"),
    Rule(frozenset({"fire", "armed"}), "shoot"),
    Rule(frozenset({"advance"}), "forward"),
    Rule(frozenset({"left"}), "left"),
    Rule(frozenset({"right"}), "right"),
)


class Explorer:
    def __init__(self):
        self.position = START
        self.heading = 0
        self.history = {}
        self.carrying = False
        self.armed = True
        self.monster_alive = True

    def knowledge(self):
        """Infer cells without pits or a living Wumpus."""
        visited = set(self.history)
        pit_free = visited.copy()
        monster_free = visited.copy()

        for cell, signals in self.history.items():
            if "breeze" not in signals:
                pit_free.update(adjacent(cell))

            if "stench" not in signals:
                monster_free.update(adjacent(cell))

        if not self.monster_alive:
            monster_free = {
                (x, y)
                for x in range(1, SIZE + 1)
                for y in range(1, SIZE + 1)
            }

        return pit_free, monster_free

    def route(self, targets, allowed):
        """Find a shortest action sequence using BFS."""
        frontier = deque([
            (self.position, self.heading, ())
        ])
        seen = {(self.position, self.heading)}

        while frontier:
            cell, facing, moves = frontier.popleft()

            if cell in targets:
                return moves

            dx, dy = HEADINGS[facing]
            ahead = (cell[0] + dx, cell[1] + dy)

            options = []

            if ahead in allowed:
                options.append(
                    (ahead, facing, "forward")
                )

            options.extend((
                (cell, (facing + 1) % 4, "left"),
                (cell, (facing - 1) % 4, "right")
            ))

            for next_cell, next_facing, action in options:
                state = (next_cell, next_facing)

                if state not in seen:
                    seen.add(state)
                    frontier.append((
                        next_cell,
                        next_facing,
                        moves + (action,)
                    ))

        return None

    def aim_or_approach(self, safe, monster_free):
        """Locate the Wumpus and plan a safe shot."""
        candidates = {
            (x, y)
            for x in range(1, SIZE + 1)
            for y in range(1, SIZE + 1)
        } - monster_free

        for cell, signals in self.history.items():
            if "stench" in signals:
                candidates &= adjacent(cell)

        if len(candidates) != 1:
            return None

        monster = next(iter(candidates))
        firing_cells = safe & adjacent(monster)

        if self.position not in firing_cells:
            return self.route(firing_cells, safe)

        offset = (
            monster[0] - self.position[0],
            monster[1] - self.position[1]
        )

        desired = HEADINGS.index(offset)
        delta = (desired - self.heading) % 4

        if delta == 0:
            return ("shoot",)

        if delta == 3:
            return ("right",)

        return ("left",)

    def step(self, percepts):
        """Update knowledge, plan, and execute one action."""
        signals = set(percepts)
        self.history[self.position] = signals.copy()

        if "scream" in signals:
            self.monster_alive = False

        facts = set(signals)
        facts.add(
            "carrying" if self.carrying else "searching"
        )

        if self.armed:
            facts.add("armed")

        if self.position == START:
            facts.add("home")

        pit_free, monster_free = self.knowledge()
        safe = pit_free & monster_free

        if self.carrying:
            targets = {START}
        else:
            targets = safe - self.history.keys()

        plan = self.route(targets, safe)

        if (
            plan is None
            and not self.carrying
            and self.armed
            and self.monster_alive
        ):
            plan = self.aim_or_approach(
                safe, monster_free
            )

        if plan:
            action_fact = {
                "forward": "advance",
                "left": "left",
                "right": "right",
                "shoot": "fire"
            }
            facts.add(action_fact[plan[0]])

        for rule in RULES:
            if not rule.applies(facts):
                continue

            action = rule.action

            if action == "grab":
                self.carrying = True

            elif action == "shoot":
                self.armed = False

            elif action == "forward":
                dx, dy = HEADINGS[self.heading]
                self.position = (
                    self.position[0] + dx,
                    self.position[1] + dy
                )

            elif action == "left":
                self.heading = (self.heading + 1) % 4

            elif action == "right":
                self.heading = (self.heading - 1) % 4

            return action

        return None


def simulate(pits, monster, treasure,
             max_steps=100, verbose=True):
    """Run one cave simulation."""
    agent = Explorer()
    monster_alive = True
    scream = False
    arrows_used = 0

    for turn in range(1, max_steps + 1):
        current = agent.position
        percepts = set()

        if adjacent(current) & pits:
            percepts.add("breeze")

        if monster_alive and monster in adjacent(current):
            percepts.add("stench")

        if current == treasure and not agent.carrying:
            percepts.add("glitter")

        if scream:
            percepts.add("scream")
            scream = False

        action = agent.step(percepts)

        if verbose:
            print(f"{turn:02d} | {current} | {action}")

        if action == "shoot":
            arrows_used += 1
            dx, dy = HEADINGS[agent.heading]

            x, y = current

            # The arrow travels straight to the boundary.
            while (
                1 <= x + dx <= SIZE
                and 1 <= y + dy <= SIZE
            ):
                x += dx
                y += dy

                if (x, y) == monster and monster_alive:
                    monster_alive = False
                    scream = True
                    break

        if (
            agent.position in pits
            or (monster_alive and agent.position == monster)
        ):
            return False, turn, arrows_used

        if action == "climb":
            success = (
                agent.carrying
                and agent.position == START
            )
            return success, turn, arrows_used

        if action is None:
            return False, turn, arrows_used

    return False, max_steps, arrows_used


